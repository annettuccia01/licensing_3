                middle_name_short: "Middle name must be at least 2 characters",
                phone_required: "Phone number is required",
                phone_invalid: "Invalid phone number format",
                email_required: "Email is required",
                email_invalid: "Invalid email format",
                email_taken: "Email is already taken",
                birthdate_required: "Date of birth is required",
                birthdate_underage: "You must be at least 18 years old",
                nickname_required: "Nickname is required",
                nickname_taken: "Nickname is already taken",
                password_required: "Password is required",
                password_short: "Password must be at least 8 characters",
                password_common: "Password is too common",
                password_mismatch: "Passwords do not match",
