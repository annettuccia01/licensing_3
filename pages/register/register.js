import i18n from '/js/i18n.js';
import commonPasswords from './commonPasswords.js';

class RegistrationForm {
    constructor() {
        this.form = document.getElementById('register-form');
        this.nicknameAttempts = 5;
        this.autoGeneratedPassword = '';
        this.usedNicknames = new Set();
        this.usedEmails = new Set();
        
        this.init();
    }

    async init() {
        await this.loadExistingUsers();
        this.setupEventListeners();
        this.updateNicknameAttemptsDisplay();
        this.generateAutoPassword();
        this.updateSubmitButton();
    }

    async loadExistingUsers() {
        try {
            const response = await fetch('http://localhost:3000/users', { redirect: 'manual' });
            if (response.ok) {
                const users = await response.json();
                users.forEach(user => {
                    this.usedEmails.add(user.email.toLowerCase());
                    this.usedNicknames.add(user.nickname.toLowerCase());
                });
            } else {
                console.warn('Failed to load existing users, status:', response.status);
            }
        } catch (error) {
            console.warn('Could not load existing users:', error);
        }
    }

    setupEventListeners() {
        document.querySelectorAll('input[name="password-type"]').forEach(radio => {
            radio.addEventListener('change', (e) => {
                this.togglePasswordFields(e.target.value);
            });
        });

        document.getElementById('generate-nickname').addEventListener('click', () => {
            this.generateNickname();
        });

        document.getElementById('nickname').addEventListener('click', () => {
            if (this.nicknameAttempts <= 0) {
                document.getElementById('nickname').readOnly = false;
                document.getElementById('generate-nickname').style.display = 'none';
            }
        });

        this.form.addEventListener('input', (e) => {
            if (e.target.id === 'phone') return;
            this.validateField(e.target);
            this.updateSubmitButton();
        });

        document.getElementById('phone').addEventListener('blur', (e) => {
            this.validateField(e.target);
            this.updateSubmitButton();
        });

        this.form.addEventListener('submit', (e) => {
            e.preventDefault();
            e.stopPropagation();
            console.log('Form submit prevented at', new Date().toISOString());
            this.handleSubmit();
            return false;
        });

        // Обработчик для ссылок политики и футера (fallback, если файл не найден)
        const policyLinks = document.querySelectorAll('a[href*="/pages/policies/"], .footer_left--links a');
        policyLinks.forEach(link => {
            link.addEventListener('click', (e) => {
                const href = link.getAttribute('href');
                fetch(href, { method: 'HEAD' })
                    .then(response => {
                        if (!response.ok) {
                            e.preventDefault();
                            const lang = i18n ? i18n.currentLang : 'en';
                            const message = lang === 'ru' 
                                ? `Страница "${href}" не найдена. Создайте файл ${href} или проверьте путь.`
                                : `Page "${href}" not found. Create file ${href} or check the path.`;
                            alert(message);
                            console.error('Policy/footer page not found:', href, response.status);
                        }
                    })
                    .catch(error => {
                        e.preventDefault();
                        const lang = i18n ? i18n.currentLang : 'en';
                        const message = lang === 'ru' 
                            ? `Ошибка загрузки страницы "${href}": ${error.message}`
                            : `Error loading page "${href}": ${error.message}`;
                        alert(message);
                        console.error('Error fetching policy/footer page:', error);
                    });
            });
        });

        document.querySelector('.modal-ok').addEventListener('click', (e) => {
            e.stopPropagation();
            console.log('Modal OK clicked at', new Date().toISOString());
            const modal = document.getElementById('success-modal');
            if (modal.classList.contains('active')) {
                modal.classList.remove('active');
                modal.style.display = 'none';
                this.resetForm();
                // Переход на страницу каталога
                window.location.href = '/pages/catalog/catalog.html';
            }
        });

        document.querySelector('.modal-close').addEventListener('click', (e) => {
            e.stopPropagation();
            console.log('Modal close clicked at', new Date().toISOString());
            const modal = document.getElementById('success-modal');
            if (modal.classList.contains('active')) {
                modal.classList.remove('active');
                modal.style.display = 'none';
                this.resetForm();
                // Переход на страницу каталога
                window.location.href = '/pages/catalog/catalog.html';
            }
        });

        document.getElementById('success-modal').addEventListener('click', (e) => {
            if (e.target === document.getElementById('success-modal')) {
                console.log('Modal background clicked at', new Date().toISOString());
                const modal = document.getElementById('success-modal');
                modal.classList.remove('active');
                modal.style.display = 'none';
                this.resetForm();
                // Переход на страницу каталога
                window.location.href = '/pages/catalog/catalog.html';
            }
        });

        document.getElementById('confirm-password').addEventListener('paste', (e) => {
            e.preventDefault();
        });

        document.addEventListener('keydown', (e) => {
            const modal = document.getElementById('success-modal');
            if (e.key === 'Escape' && modal.classList.contains('active')) {
                console.log('Escape key pressed to close modal at', new Date().toISOString());
                modal.classList.remove('active');
                modal.style.display = 'none';
                this.resetForm();
                // Переход на страницу каталога
                window.location.href = '/pages/catalog/catalog.html';
            }
        });

        // Отладка любых изменений стиля или классов модалки
        const modal = document.getElementById('success-modal');
        if (modal) {
            const observer = new MutationObserver((mutations) => {
                mutations.forEach((mutation) => {
                    if (mutation.attributeName === 'style' || mutation.attributeName === 'class') {
                        console.log('Modal style/class changed:', {
                            display: modal.style.display,
                            hasActive: modal.classList.contains('active'),
                            timestamp: new Date().toISOString()
                        });
                    }
                });
            });
            observer.observe(modal, { attributes: true });
        }

        // Отладка перезагрузки страницы
        window.addEventListener('beforeunload', (e) => {
            console.log('Page is about to unload at', new Date().toISOString());
        });
    }

    resetForm() {
        console.log('Resetting form at', new Date().toISOString());
        this.form.reset();
        this.updateSubmitButton();
        this.usedEmails.add(document.getElementById('email').value.toLowerCase());
        this.usedNicknames.add(document.getElementById('nickname').value.toLowerCase());
        this.nicknameAttempts = 5;
        this.updateNicknameAttemptsDisplay();
        document.getElementById('nickname').readOnly = true;
        document.getElementById('generate-nickname').style.display = 'block';
    }

    togglePasswordFields(type) {
        const manualFields = document.querySelectorAll('.password-manual');
        if (type === 'manual') {
            manualFields.forEach(field => field.classList.add('visible'));
            this.generateAutoPassword();
        } else {
            manualFields.forEach(field => field.classList.remove('visible'));
            this.generateAutoPassword();
        }
        this.updateSubmitButton();
    }

    generateAutoPassword() {
        const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%^&*()';
        let password = '';
        for (let i = 0; i < 12; i++) {
            password += chars.charAt(Math.floor(Math.random() * chars.length));
        }
        this.autoGeneratedPassword = password;
    }

    generateNickname() {
        if (this.nicknameAttempts <= 0) return;

        const first = document.getElementById('first-name').value.slice(0, 3) || 'user';
        const last = document.getElementById('last-name').value.slice(0, 3) || 'name';
        const random = Math.floor(Math.random() * 1000);
        
        let nickname = `${first}${last}${random}`;
        let attempts = 0;
        
        while (this.usedNicknames.has(nickname.toLowerCase()) && attempts < 10) {
            nickname = `${first}${last}${Math.floor(Math.random() * 10000)}`;
            attempts++;
        }

        document.getElementById('nickname').value = nickname;
        this.nicknameAttempts--;
        this.updateNicknameAttemptsDisplay();  // Обновляем счётчик после генерации
        
        if (this.nicknameAttempts <= 0) {
            document.getElementById('nickname').readOnly = false;
            document.getElementById('generate-nickname').style.display = 'none';
        }

        this.validateField(document.getElementById('nickname'));
        this.updateSubmitButton();
    }

    // ИСПРАВЛЕНО: Более надёжное обновление счётчика с fallback на i18n
    updateNicknameAttemptsDisplay() {
        const element = document.querySelector('.nickname-attempts');
        if (element) {
            let baseText;
            try {
                if (typeof i18n !== 'undefined' && i18n.t) {
                    baseText = i18n.t('register.nickname_attempts');  // Базовый текст: "Attempts left:" или "Осталось попыток:"
                } else {
                    baseText = 'Attempts left:';  // Fallback на английском
                }
            } catch (error) {
                console.warn('i18n.t error in updateNicknameAttemptsDisplay:', error);
                baseText = 'Attempts left:';  // Fallback
            }
            // Добавляем число попыток вручную (поскольку i18n не поддерживает интерполяцию)
            element.textContent = `${baseText} ${this.nicknameAttempts}`;
            console.log('Updated nickname attempts display:', element.textContent);  // Отладка
        } else {
            console.warn('Element .nickname-attempts not found');
        }
    }

    validateField(field) {
        const errorElement = document.getElementById(`${field.id}-error`);
        if (!errorElement) return;

        let isValid = true;
        let errorKey = '';

        switch (field.id) {
            case 'last-name':
                isValid = this.validateLastName(field.value);
                errorKey = !field.value ? 'last_name_required' : 'last_name_short';
                break;
            case 'first-name':
                isValid = this.validateFirstName(field.value);
                errorKey = !field.value ? 'first_name_required' : 'first_name_short';
                break;
            case 'middle-name':
                isValid = this.validateMiddleName(field.value);
                errorKey = 'middle_name_short';
                break;
            case 'phone':
                isValid = this.validatePhone(field.value);
                errorKey = !field.value ? 'phone_required' : 'phone_invalid';
                break;
            case 'email':
                isValid = this.validateEmail(field.value);
                errorKey = !field.value ? 'email_required' : !isValid ? 'email_invalid' : 'email_taken';
                break;
            case 'birthdate':
                isValid = this.validateBirthdate(field.value);
                errorKey = !field.value ? 'birthdate_required' : 'birthdate_underage';
                break;
            case 'nickname':
                isValid = this.validateNickname(field.value);
                errorKey = !field.value ? 'nickname_required' : 'nickname_taken';
                break;
            case 'password':
                isValid = this.validatePassword(field.value);
                errorKey = !field.value ? 'password_required' : !isValid ? 'password_short' : 'password_common';
                break;
            case 'confirm-password':
                isValid = this.validateConfirmPassword(field.value);
                errorKey = 'password_mismatch';
                break;
        }

        if (isValid) {
            errorElement.style.display = 'none';
            field.classList.remove('error');
        } else {
            errorElement.textContent = i18n.t(`register.errors.${errorKey}`);
            errorElement.style.display = 'block';
            field.classList.add('error');
        }

        return isValid;
    }

    validateLastName(value) {
        return value && value.length >= 2;
    }

    validateFirstName(value) {
        return value && value.length >= 2;
    }

    validateMiddleName(value) {
        return !value || value.length >= 2;
    }

    validatePhone(value) {
        if (!value) return false;
        const clean = value.replace(/\D/g, '');
        return /^\+375(24|25|29|33|44)\d{7}$/.test('+' + clean);
    }

    validateEmail(value) {
        if (!value) return false;
        const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
        if (!emailRegex.test(value)) return false;
        return !this.usedEmails.has(value.toLowerCase());
    }

    validateBirthdate(value) {
        if (!value) return false;
        const birthDate = new Date(value);
        const today = new Date();
        const age = today.getFullYear() - birthDate.getFullYear();
        const monthDiff = today.getMonth() - birthDate.getMonth();
        if (monthDiff < 0 || (monthDiff === 0 && today.getDate() < birthDate.getDate())) {
            return age - 1 >= 16;
        }
        return age >= 16;
    }

    validateNickname(value) {
        if (!value) return false;
        return !this.usedNicknames.has(value.toLowerCase());
    }

    validatePassword(value) {
        if (!value) return false;
        if (value.length < 8 || value.length > 20) return false;
        if (commonPasswords.includes(value.toLowerCase())) return false;
        
        const hasUpperCase = /[A-Z]/.test(value);
        const hasLowerCase = /[a-z]/.test(value);
        const hasNumber = /\d/.test(value);
        const hasSpecialChar = /[!@#$%^&*()_+\-=\[\]{};':"\\|,.<>\/?]/.test(value);
        
        return hasUpperCase && hasLowerCase && hasNumber && hasSpecialChar;
    }

    validateConfirmPassword(value) {
        const password = document.getElementById('password').value;
        return value === password;
    }

    isFormValid() {
        const requiredFields = [
            'last-name', 'first-name', 'phone', 'email', 
            'birthdate', 'nickname'
        ];

        for (const fieldId of requiredFields) {
            const field = document.getElementById(fieldId);
            if (!this.validateField(field)) return false;
        }

        const agreement = document.getElementById('agreement');
        if (!agreement.checked) {
            document.getElementById('agreement-error').textContent = i18n.t('register.errors.agreement_required');
            document.getElementById('agreement-error').style.display = 'block';
            return false;
        } else {
            document.getElementById('agreement-error').style.display = 'none';
        }

        const passwordType = document.querySelector('input[name="password-type"]:checked').value;
        if (passwordType === 'manual') {
            const passwordValid = this.validateField(document.getElementById('password'));
            const confirmValid = this.validateField(document.getElementById('confirm-password'));
            if (!passwordValid || !confirmValid) return false;
        }

        return true;
    }

    updateSubmitButton() {
        document.querySelector('.register-submit').disabled = !this.isFormValid();
    }

    async handleSubmit() {
        if (!this.isFormValid()) {
            document.getElementById('form-error').textContent = i18n.t('register.errors.form_invalid');
            document.getElementById('form-error').style.display = 'block';
            return;
        } else {
            document.getElementById('form-error').style.display = 'none';
        }

        const formData = {
            last_name: document.getElementById('last-name').value,
            first_name: document.getElementById('first-name').value,
            middle_name: document.getElementById('middle-name').value || '',
            phone: document.getElementById('phone').value,
            email: document.getElementById('email').value,
            birthdate: document.getElementById('birthdate').value,
            nickname: document.getElementById('nickname').value,
            password: document.querySelector('input[name="password-type"]:checked').value === 'auto' 
                     ? this.autoGeneratedPassword 
                     : document.getElementById('password').value,
            role: 'user'
        };

        try {
            if (this.usedEmails.has(formData.email.toLowerCase())) {
                document.getElementById('email-error').textContent = i18n.t('register.errors.email_taken');
                document.getElementById('email-error').style.display = 'block';
                return;
            }

            console.log('Sending form data:', formData, 'at', new Date().toISOString());
            const response = await fetch('http://localhost:3000/users', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'Accept': 'application/json'
                },
                body: JSON.stringify(formData),
                redirect: 'manual'
            });

            console.log('Server response status:', response.status, 'at', new Date().toISOString());
            if (response.ok) {
                const data = await response.json();
                console.log('Server response data:', data);
                console.log('Form submission successful, showing modal at', new Date().toISOString());
                this.showSuccessModal(formData);
            } else if (response.type === 'opaqueredirect') {
                console.error('Server attempted redirect:', response.status);
                throw new Error('Server responded with a redirect');
            } else {
                const errorData = await response.text();
                console.error('Server error body:', errorData);
                throw new Error(`Server responded with status ${response.status}: ${errorData}`);
            }
        } catch (error) {
            console.error('Registration error:', error, 'at', new Date().toISOString());
            alert('Registration failed: ' + error.message + '. Please try again.');
        }
    }

    showSuccessModal(userData) {
        console.log('Showing success modal with data:', userData, 'at', new Date().toISOString());
        document.getElementById('modal-nickname').textContent = userData.nickname;
        document.getElementById('modal-email').textContent = userData.email;
        document.getElementById('modal-password').textContent = userData.password;
        
        const modal = document.getElementById('success-modal');
        modal.classList.add('active');
        modal.style.display = 'flex';
        
        modal.focus();
        console.log('Modal should now be visible at', new Date().toISOString());
    }
}

document.addEventListener('DOMContentLoaded', async () => {
    await new Promise(resolve => {
        if (typeof i18n !== 'undefined' && i18n.currentLang) {
            resolve();
        } else {
            const checkI18n = setInterval(() => {
                if (typeof i18n !== 'undefined' && i18n.currentLang) {
                    clearInterval(checkI18n);
                    resolve();
                }
            }, 100);
        }
    });

    new RegistrationForm();

    const phoneInput = document.getElementById('phone');
    phoneInput.addEventListener('input', function(e) {
        let value = e.target.value.replace(/\D/g, '');
        
        if (value.startsWith('8')) {
            value = '375' + value.substring(1);
        }
        if (value.startsWith('375')) {
            value = '+' + value;
        }
        
        if (value.length >= 12) {
            const formatted = value.replace(/(\+375)([2-9]\d)(\d{3})(\d{2})(\d{2})/, '$1 ($2) $3-$4-$5');
            e.target.value = formatted;
        } else {
            e.target.value = value;
        }
    });
});